#!/bin/bash

if [ $# -lt 3 ] || [ $# -gt 4 ]; then
  echo "Usage: $0 <input directory> <output directory> <resource directory> [custom templates directory]" >&2
  exit 1
fi

incunable_folder="$(readlink -f "$0")"
input="$(           readlink -f "$1")"
output="$(          readlink -f "$2")"
resource_folder="$( readlink -f "$3")"
custom_templates=""
if [ -n "$4" ]; then
  custom_templates="$(readlink -f "$4")"
fi

if [ ! -d "$input" ]; then
  echo "Error: The input directory '$1' does not exist." >&2
  exit 1
fi
if [ ! -f "$resource_folder/header" ] || [ ! -f "$resource_folder/footer" ]; then
  echo "Error: The resource directory '$3' must contain the files 'header' and 'footer'." >&2
  exit 1
fi
if [ -n "$4" ] && [ ! -d "$custom_templates" ]; then
  echo "Error: The custom templates directory '$4' does not exist." >&2
  exit 1
fi

for dependency in gawk cmark-gfm; do
  if ! command -v "$dependency" &>/dev/null; then
    echo "Error: $dependency is not installed." >&2
    exit 1
  fi
done
if command -v python3 &>/dev/null; then
  PYTHON=python3
elif command -v python &>/dev/null; then
  PYTHON=python
else
  echo "Error: Python is not installed." >&2
  exit 1
fi

prev_dir="$(pwd)"
cd "$(dirname "$incunable_folder")/.." || exit 1

# All temporary files are kept in a directory of their own, which is removed when the script exits. This way,
# several instances can run at the same time without overwriting each others files.
workdir="$(mktemp -d)" || exit 1
trap 'rm -rf "$workdir"' EXIT

templatedir="$workdir/templates/"
mkdir "$templatedir"
cp -r html/templates/* "$templatedir"
if [ -n "$custom_templates" ]; then
  cp -r "$custom_templates"/* "$templatedir"
fi

# The order in which to run the pre-processing scripts is the same for every page, so it is calculated only once.
if ! pre_script_order="$($PYTHON pre-script-runner.py "$templatedir")"; then
  exit 1
fi
pre_scripts=()
if [ -n "$pre_script_order" ]; then
  mapfile -t pre_scripts <<< "$pre_script_order"
fi

# A pre-processing script is only run on pages that contain a template it handles, since starting a
# script is costly. A script handles the template it is named after, and any templates listed on a
# line starting with "# @handles". Scripts with a line starting with "# @always" are run on every page.
declare -A always_run handled_templates
for script in "${pre_scripts[@]}"; do
  handled_templates["$script"]="$script"
  while IFS= read -r line; do
    if [[ "$line" =~ ^#\ *@always ]]; then
      always_run["$script"]=1
    elif [[ "$line" =~ ^#\ *@handles(.*)$ ]]; then
      handled_templates["$script"]+=",${BASH_REMATCH[1]}"
    fi
  done < "${templatedir}pre/$script"
done

# Runs the pre-processing scripts on the page currently being compiled.
function run_pre_scripts() {
  local script content template templates found
  for script in "${pre_scripts[@]}"; do
    if [ -z "${always_run[$script]}" ]; then
      # The page is read anew for each script, as earlier scripts may have written new templates to it
      content="$(<"$tmp_name")"
      found=0
      IFS=',' read -ra templates <<< "${handled_templates[$script]}"
      for template in "${templates[@]}"; do
        template="${template//[[:space:]]/}"
        if [ -n "$template" ] && [[ "$content" == *"{{$template"* ]]; then
          found=1
          break
        fi
      done
      if [ $found -eq 0 ]; then
        continue
      fi
    fi
    if ! "${templatedir}pre/$script" "$tmp_name" "$basename" "$additionalfiles" "$input"; then
      echo "Error: The pre-processing script '$script' failed for $target" >&2
      return 1
    fi
  done
}

# Each directory with an index.md file is a page to compile. The targets are read
# line by line, so that directory names containing spaces are kept intact.
mapfile -t targets < <(find "${input}" -mindepth 2 -type f -name "index.md" -printf '%P\n' | sed -r "s|/index.md$||")

mkdir -p "$output"
cp -r "$resource_folder"/* "$output"
# The header and footer are not part of the output; they are instead inserted into each page
rm -f "$output"/header "$output"/footer
export INCUNABLE_TEMPLATE_DIR="$templatedir"

# Compiles the page given as the first argument. The second argument
# is a directory for the temporary files of the page.
function compile_page() {
  local target="$1" pagedir="$2"
  local subdirs nesting c basename tmp_name tmp_body additionalfiles title custom_scripts custom_css
  local result=0

  echo "Compiling $target"

  subdirs="${target//[^\/]}"
  nesting=""
  for (( c=1; c<=${#subdirs}; c++ )); do
    nesting="${nesting}../"
  done
  basename="${target##*/}"
  mkdir "$pagedir"
  tmp_name="$pagedir/${basename}"
  tmp_body="$pagedir/body.html"

  additionalfiles="${output}/${target}-files"
  mkdir -p "$additionalfiles"
  # Remove any iframe.js generated by a previous run, or the include-iframe
  # pre-script will believe that the page has provided its own.
  rm -f "$additionalfiles"/iframe.js
  cp "$input/$target/index.md" "$output/$target.md"
  cp -r "$input/$target"/* "$additionalfiles"
  mv "$additionalfiles"/index.md "$tmp_name"

  if ! run_pre_scripts; then
    result=1
  fi
  # Find the title of the page, and the scripts and stylesheets it includes
  {
    IFS= read -r title
    IFS= read -r custom_scripts
    IFS= read -r custom_css
  } < <(awk '
    /^#/ && !title_found       { title = $0; sub(/^# */, "", title); title_found = 1 }
    $0 ~ "{{include-script"    { sub("}}", "", $2); scripts = scripts substr($2, index($2, "=") + 1) " " }
    $0 ~ "{{include-css"       { sub("}}", "", $2); css     = css     substr($2, index($2, "=") + 1) " " }
    END                        { print title; print scripts; print css }
    ' "$tmp_name")

  # The softbreak template is turned into a newline only after the Markdown has been
  # processed, so that it does not affect how the Markdown is interpreted.
  ./template_substituter.awk "$tmp_name" \
    | cmark-gfm -e table -e strikethrough -e footnotes --table-prefer-style-attributes --unsafe \
    | sed -e 's/&amp;/\&/g' -e 's/&incunable-softbreak;/\n/g' > "$tmp_body"

  # Put the header, the page and the footer together, substituting the variables of the header and footer.
  # The values are passed through the environment rather than with -v, since awk would otherwise interpret
  # any backslashes in them as escape sequences.
  INCUNABLE_TITLE="$title" INCUNABLE_PATH="$target" INCUNABLE_FILENAME="$basename" INCUNABLE_SOURCEDIR="$additionalfiles" \
  INCUNABLE_NESTING="$nesting" INCUNABLE_SCRIPTS="$custom_scripts" INCUNABLE_CSS="$custom_css" INCUNABLE_BODY="$tmp_body" \
  awk -i "utils.awk" '
    BEGIN {
      title     = ENVIRON["INCUNABLE_TITLE"]
      path      = ENVIRON["INCUNABLE_PATH"]
      filename  = ENVIRON["INCUNABLE_FILENAME"]
      sourcedir = ENVIRON["INCUNABLE_SOURCEDIR"]
      nesting   = ENVIRON["INCUNABLE_NESTING"]
      body      = ENVIRON["INCUNABLE_BODY"]
      folder    = filename "-files/"

      css = ""
      scripts = ""
      n = split(ENVIRON["INCUNABLE_CSS"], c, " ")
      for (i = 1; i <= n; i++) css = css "  <link rel=\"stylesheet\" type=\"text/css\" href=\"" folder c[i] "\" />\n"
      n = split(ENVIRON["INCUNABLE_SCRIPTS"], s, " ")
      for (i = 1; i <= n; i++) scripts = scripts "  <script src=\"" folder s[i] "\"></script>\n"
    }
    FILENAME == body {
      # The page itself is already finished
      print $0
      next
    }
    {
      $0 = replace_literal($0, "${nesting}", nesting)
      if (FNR == NR) {
        # Only the header is read at this point
        $0 = replace_literal($0, "</head>", css scripts "</head>")
        type = "header"
      } else {
        type = "footer"
      }

      if (match($0, "\\$\\{include-" type "-([0-9]+)\\}", arr)) {
        $0 = replace_literal($0, "${include-" type "-" arr[1] "}", read_file(sourcedir "/_include-" type "-" arr[1]))
      }
      $0 = replace_literal($0, "${path}",     path)
      $0 = replace_literal($0, "${title}",    title)
      $0 = replace_literal($0, "${filename}", filename)
      print $0
    }' "$resource_folder"/header "$tmp_body" "$resource_folder"/footer > "$output/$target.html"

  rm -rf "$pagedir" "$additionalfiles"/reflist
  return $result
}

# The pages do not depend on each other, so several are compiled at the same time. The number of simultaneous
# pages defaults to the number of processors, and can be set with the environment variable INCUNABLE_JOBS.
max_jobs="${INCUNABLE_JOBS:-$(nproc 2>/dev/null || echo 1)}"
if ! [[ "$max_jobs" =~ ^[1-9][0-9]*$ ]]; then
  echo "Error: INCUNABLE_JOBS must be a positive number, but is '$max_jobs'." >&2
  exit 1
fi

running_jobs=0
page_number=0
for target in "${targets[@]}"; do
  if [ "$running_jobs" -ge "$max_jobs" ]; then
    wait -n
    running_jobs=$((running_jobs - 1))
  fi
  page_number=$((page_number + 1))
  # Pages that fail leave a marker file behind, since the exit status of a background job is cumbersome to collect
  ( compile_page "$target" "$workdir/page-$page_number" || touch "$workdir/failed" ) &
  running_jobs=$((running_jobs + 1))
done
wait

exit_code=0
if [ -e "$workdir/failed" ]; then
  exit_code=1
fi
cd "$prev_dir" || exit 1

exit $exit_code
