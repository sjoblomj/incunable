#!/bin/bash

if [ $# -lt 3 ] || [ $# -gt 4 ]; then
  echo "Usage: $0 <input directory> <output directory> <resource directory> [custom templates directory]" >&2
  exit 1
fi

incunable_folder="$(readlink -f "$0")"
input="$(           readlink -f "$1")"
output="$(          readlink -f "$2")"
resource_folder="$( readlink -f "$3")"
custom_templates=""
if [ -n "$4" ]; then
  custom_templates="$(readlink -f "$4")"
fi

if [ ! -d "$input" ]; then
  echo "Error: The input directory '$1' does not exist." >&2
  exit 1
fi
if [ ! -f "$resource_folder/header" ] || [ ! -f "$resource_folder/footer" ]; then
  echo "Error: The resource directory '$3' must contain the files 'header' and 'footer'." >&2
  exit 1
fi
if [ -n "$4" ] && [ ! -d "$custom_templates" ]; then
  echo "Error: The custom templates directory '$4' does not exist." >&2
  exit 1
fi

for dependency in gawk cmark-gfm; do
  if ! command -v "$dependency" &>/dev/null; then
    echo "Error: $dependency is not installed." >&2
    exit 1
  fi
done
if command -v python3 &>/dev/null; then
  PYTHON=python3
elif command -v python &>/dev/null; then
  PYTHON=python
else
  echo "Error: Python is not installed." >&2
  exit 1
fi

prev_dir="$(pwd)"
cd "$(dirname "$incunable_folder")/.." || exit 1

# All temporary files are kept in a directory of their own, which is removed when the script exits. This way,
# several instances can run at the same time without overwriting each others files.
workdir="$(mktemp -d)" || exit 1
trap 'rm -rf "$workdir"' EXIT

templatedir="$workdir/templates/"
mkdir "$templatedir"
cp -r html/templates/* "$templatedir"
if [ -n "$custom_templates" ]; then
  cp -r "$custom_templates"/* "$templatedir"
fi

# The order in which to run the pre-processing scripts is the same for every page, so it is calculated only once.
if ! pre_script_order="$($PYTHON pre-script-runner.py "$templatedir")"; then
  exit 1
fi
pre_scripts=()
if [ -n "$pre_script_order" ]; then
  mapfile -t pre_scripts <<< "$pre_script_order"
fi

# Runs the pre-processing scripts on the page currently being compiled.
function run_pre_scripts() {
  local script
  for script in "${pre_scripts[@]}"; do
    if ! "${templatedir}pre/$script" "$tmp_name" "$basename" "$additionalfiles" "$input"; then
      echo "Error: The pre-processing script '$script' failed for $target" >&2
      return 1
    fi
  done
}

# Each directory with an index.md file is a page to compile. The targets are read
# line by line, so that directory names containing spaces are kept intact.
mapfile -t targets < <(find "${input}" -mindepth 2 -type f -name "index.md" -printf '%P\n' | sed -r "s|/index.md$||")

mkdir -p "$output"
cp -r "$resource_folder"/* "$output"
# The header and footer are not part of the output; they are instead inserted into each page
rm -f "$output"/header "$output"/footer
exit_code=0
for target in "${targets[@]}"; do

  echo "Compiling $target"

  subdirs="${target//[^\/]}"
  nesting=""
  for (( c=1; c<=${#subdirs}; c++ )); do
    nesting="${nesting}../"
  done
  basename=$(basename "$target")
  tmp_name="$workdir/${basename}"
  tmp_header="$workdir/header"
  tmp_footer="$workdir/footer"

  additionalfiles="${output}/${target}-files"
  mkdir -p "$additionalfiles"
  # Remove any iframe.js generated by a previous run, or the include-iframe
  # pre-script will believe that the page has provided its own.
  rm -f "$additionalfiles"/iframe.js
  cp "$input/$target/index.md" "$output/$target.md"
  cp -r "$input/$target"/* "$additionalfiles"
  mv "$additionalfiles"/index.md "$tmp_name"

  if ! run_pre_scripts; then
    exit_code=1
  fi
  title=$(grep -oP '^# *\K.*' "$tmp_name" | head -n 1)
  custom_scripts=$(awk '{if ($0 ~ "{{include-script") { sub("}}", "", $2); file = substr($2, index($2, "=") + 1); print file;}}' "$tmp_name")
  custom_css=$(    awk '{if ($0 ~ "{{include-css")    { sub("}}", "", $2); file = substr($2, index($2, "=") + 1); print file;}}' "$tmp_name")

  export INCUNABLE_TEMPLATE_DIR="$templatedir"
  ./template_substituter.awk "$tmp_name" > "${tmp_name}_2" && mv "${tmp_name}_2" "$tmp_name"
  cmark-gfm -e table -e strikethrough -e footnotes --table-prefer-style-attributes --unsafe "$tmp_name" > "${tmp_name}_2" && mv "${tmp_name}_2" "$tmp_name"
  # The softbreak template is turned into a newline only after the Markdown has been
  # processed, so that it does not affect how the Markdown is interpreted.
  sed -i -e 's/&amp;/\&/g' -e 's/&incunable-softbreak;/\n/g' "$tmp_name"
  unset INCUNABLE_TEMPLATE_DIR


  sed -e "s|\${nesting}|${nesting}|g" "$resource_folder"/header > "$tmp_header"
  sed -e "s|\${nesting}|${nesting}|g" "$resource_folder"/footer > "$tmp_footer"
  # The values are passed through the environment rather than with -v, since awk would otherwise interpret
  # any backslashes in them as escape sequences.
  export INCUNABLE_TITLE="$title" INCUNABLE_PATH="$target" INCUNABLE_FILENAME="$basename" INCUNABLE_SOURCEDIR="$additionalfiles"
  awk -v folder="$basename-files/" -v custom_css="$custom_css" -v custom_scripts="$custom_scripts" -i "utils.awk" -i inplace '
    BEGIN {
      title     = ENVIRON["INCUNABLE_TITLE"]
      path      = ENVIRON["INCUNABLE_PATH"]
      filename  = ENVIRON["INCUNABLE_FILENAME"]
      sourcedir = ENVIRON["INCUNABLE_SOURCEDIR"]
    }
    {
    css = ""
    scripts = ""
    split(custom_css, c, " ")
    split(custom_scripts, s, " ")

    for (i in c) css = css "  <link rel=\"stylesheet\" type=\"text/css\" href=\"" folder c[i] "\" />\n"
    for (i in s) scripts = scripts "  <script src=\"" folder s[i] "\"></script>\n"
    $0 = replace_literal($0, "</head>", css scripts "</head>")

    if (match($0, /\$\{include-header-([0-9]+)\}/, arr)) {
        $0 = replace_literal($0, "${include-header-" arr[1] "}", read_file(sourcedir "/_include-header-" arr[1]))
    }
    $0 = replace_literal($0, "${path}",     path)
    $0 = replace_literal($0, "${title}",    title)
    $0 = replace_literal($0, "${filename}", filename)
    print $0
    }' "$tmp_header"

  awk -i "utils.awk" -i inplace '
    BEGIN {
      title     = ENVIRON["INCUNABLE_TITLE"]
      path      = ENVIRON["INCUNABLE_PATH"]
      filename  = ENVIRON["INCUNABLE_FILENAME"]
      sourcedir = ENVIRON["INCUNABLE_SOURCEDIR"]
    }
    {
    if (match($0, /\$\{include-footer-([0-9]+)\}/, arr)) {
        $0 = replace_literal($0, "${include-footer-" arr[1] "}", read_file(sourcedir "/_include-footer-" arr[1]))
    }
    $0 = replace_literal($0, "${path}",     path)
    $0 = replace_literal($0, "${title}",    title)
    $0 = replace_literal($0, "${filename}", filename)
    print $0
    }' "$tmp_footer"
  cat "$tmp_header" "$tmp_name" "$tmp_footer" > "$output/$target.html"

  unset INCUNABLE_TITLE INCUNABLE_PATH INCUNABLE_FILENAME INCUNABLE_SOURCEDIR
  rm "$tmp_header" "$tmp_footer" "$tmp_name"
  rm -f "$additionalfiles"/reflist
done
cd "$prev_dir" || exit 1

exit $exit_code
